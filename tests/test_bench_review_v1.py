"""Дефекты генератора среди ложных тревог v1: правила узнают свои находки и не трогают чужие."""

import pytest

from zerocycle.bench.review_v1 import classify


def f(description: str, basis: str = "") -> dict:
    return {"description": description, "basis": basis}


@pytest.mark.parametrize(
    ("text", "defect"),
    [
        ("На титульном листе наименование объекта написано строчными буквами и с кавычками.", "G01"),
        ("В конце содержания тома нет общего количества листов тома.", "G02"),
        ("В содержании тома нет итога — общего количества листов тома.", "G02"),
        ("«Состав проектной документации» выделен отдельным томом, но у него нет титульного листа.", "G03"),
        ("На титульных листах в полях 9–11 только фамилии: дат подписания и подписей нет.", "G04"),
        ("Наименование документа в содержании тома не совпадает с основной надписью.", "G05"),
        ("Ведомость графической части перечисляет только листы 1–26, а в документе 29 листов.", "G06"),
        ("Номер листа повторяется: номер 36 стоит и на с. 37, и на с. 38.", "G07"),
        ("В таблице нагрузок полезная нагрузка 1,50 кПа, в тексте — 2,0 кПа.", "G08"),
        ("Установленная мощность 497 кВт, расчётная 480 кВт; в тексте расчётная — 497 кВт.", "G09"),
        ("Раздел 12 отмечен «Не разрабатывается», а задание на проектирование требует смету.", "G10"),
        ("Площадь застройки 2 136,8 м², а задание ограничивает: не более 2 136 м².", "G11"),
        ("Сводный сметный расчёт без итогов и НДС: заявленная стоимость не прослеживается.", "G12"),
        ("В содержании тома 12 у сметных документов не указаны обозначения.", "G13"),
    ],
)
def test_generator_defects(text, defect):
    assert classify(f(text)) == defect


@pytest.mark.parametrize(
    "text",
    [
        "В графе 26 указано «А2», а лист фактически А3 (297×420 мм).",
        "Ссылка на СНиП 23-05-95, хотя действует СП 52.13330.2016.",
        "Лист сохранён в PDF повёрнутым на 90°: флага поворота нет.",
        "Основная надпись тома выполнена не по общей форме: без «Кол.уч.».",
        "В info.xml нет раздела 6 «Технологические решения».",
    ],
)
def test_real_false_alarms_stay(text):
    assert classify(f(text)) is None
