def test_dedupe_and_cluster_share():
    from zerocycle.remarks.conclusion import Conclusion, Remark
    from zerocycle.remarks.measure import cluster_share, dedupe, remark_key

    def concl(number, sha, texts):
        rem = [Remark(n=i, text=t, page=1) for i, t in enumerate(texts, start=1)]
        return Conclusion(
            file=f"{sha}.pdf", sha256=sha * 64, pages=1, text_pages=1, number=number, status="ok", remarks=rem
        )

    items = [f"Представлен расчет №{i}." for i in range(6)]
    a, b = concl("A-1", "a", items), concl("A-2", "b", [*items[:5], "Другой пункт."])  # 5 из 7 общих: 71% — не копия
    c, d = concl("A-3", "c", items), concl("A-1", "d", ["Один пункт."])  # c — копия списка a, d — тот же номер
    kept, copies = dedupe([a, b, c, d])
    assert {k.number for k in kept} == {"A-1", "A-2"} and len(copies) == 2
    key = remark_key(a, a.remarks[0])  # от номера пункта, страницы, регистра и пробелов не зависит
    assert key == remark_key(a, Remark(n=9, text="  представлен   расчет №0. ", page=3))
    assert key != remark_key(c, c.remarks[0])  # тот же текст в другом заключении — другой пункт
    s = cluster_share([(1, 2), (3, 4), (0, 2)], iters=500)
    assert (s.k, s.n, round(s.p, 3)) == (4, 8, 0.5) and 0.0 <= s.lo <= s.p <= s.hi <= 1.0


