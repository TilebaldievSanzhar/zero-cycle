def _pages(*bodies: str) -> list[str]:
    return [f"{body}\nСтраница {i} из {len(bodies)}\n{RUNNING}" for i, body in enumerate(bodies, start=1)]


def _parse(pages: list[str]):
    return parse_conclusion(pages, len(pages), "z.pdf", "0" * 64)


