    c = _parse(_pages(COVER, PREFACE, TITLE + "\n" + TOC, SECTION, SECTION_END))
    assert c.status == "ok"
    assert (c.number, c.issued.isoformat(), c.verdict) == ("SE-0001/26", "2026-09-11", "положительное")
