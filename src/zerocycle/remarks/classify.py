_COMPILED = [(rule, cat, re.compile(rx)) for rule, cat, rx in _RULES]
_DASHES = str.maketrans(dict.fromkeys("‐‑‒–—―−", "-"))
_LATIN = str.maketrans("aceopxyACEHKMOPTXY", "асеорхуАСЕНКМОРТХУ")
_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")
_LOOKALIKE = re.compile(r"[ACEHKMOPTXY]{2,3}")  # «CH PK» латиницей вместо «СН РК»


def _fix_latin(word: str) -> str:
    return word.translate(_LATIN) if _CYRILLIC.search(word) or _LOOKALIKE.fullmatch(word) else word


def normalize(text: str) -> str:
    """Текст для правил: строчные, «ё» → «е», тире → дефис, латиница-двойник в кириллице («Cведения») → кириллица."""
    t = " ".join(_fix_latin(w) for w in text.translate(_DASHES).split())
    return t.lower().replace("ё", "е")


@dataclass(frozen=True)
class Verdict:
    category: str
    rule: str | None  # None — ни одно правило не сработало
    tags: tuple[str, ...]  # все категории, чьи правила сработали, в порядке приоритета


def classify(text: str) -> Verdict:
    t = normalize(text)
    hits = [(rule, cat) for rule, cat, rx in _COMPILED if rx.search(t)]
    if not hits:
        return Verdict("other", None, ())
    tags = tuple(dict.fromkeys(cat for _, cat in hits if cat != "unspecified"))
    return Verdict(hits[0][1], hits[0][0], tags)


def is_formal(category: str) -> bool | None:
    return CATEGORIES[category].formal
