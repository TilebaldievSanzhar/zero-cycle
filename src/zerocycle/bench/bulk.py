def notes_block(norms: list[str], wording: str, rng: random.Random) -> tuple[list[str], bool]:
    """«Примечания» на чертеже; второе значение — есть ли там СНиП из наименования СП."""
    lines = ["Примечания:"]
    snip = False
    items = [
        "Размеры даны в миллиметрах, отметки — в метрах.",
        "Размеры уточнять по месту.",
    ]
    if norms:
        ref, snip = norm_inline(rng.choice(norms), wording, rng)
        items.insert(rng.randint(0, 2), f"Работы выполнять в соответствии с требованиями {ref}.")
    lines += [f"{i}. {s}" for i, s in enumerate(items, start=1)]
    return lines, snip


