def norm_inline(code: str, wording: str, rng: random.Random) -> tuple[str, bool]:
    """Ссылка на норму в тексте по стилю выборки; второе значение — есть ли в ней СНиП из наименования СП."""
    title = NORM_TITLES.get(code, "")
    old = title[title.index("СНиП") :] if "СНиП" in title else ""
    style = rng.choice(NORM_STYLES[wording])
    clause = f"{rng.randint(4, 9)}.{rng.randint(1, 12)}"
    if ("{title}" in style and not title) or ("{old}" in style and not old):
        style = "{code}"
    text = style.format(code=code, title=title, old=old, clause=clause)
    return text, "СНиП" in text


