def cycle(items: list[str], n: int, rng: random.Random) -> list[str]:
    """n пунктов по кругу в перемешанном порядке: без подряд идущих повторов, как в настоящем документе."""
    order = rng.sample(items, len(items))
    return [order[i % len(order)] for i in range(max(0, n))]


