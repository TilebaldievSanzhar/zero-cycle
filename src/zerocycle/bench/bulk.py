def paragraph(key: str, wording: str, rng: random.Random, fill: dict, norms: list[str]) -> tuple[str, str | None]:
    """Абзац из 1–3 предложений; второе значение — вид отвлекающего содержимого (для эталона) или None."""
    pool = GENERIC[wording] + SECTION_TEXT[wording].get(key, []) * 2
    parts = []
    kind = None
    for _ in range(rng.randint(1, 3)):
        t = rng.choice(pool)
        if "{norm}" in t:
            if not norms:
                continue
            ref, snip = norm_inline(rng.choice(norms), wording, rng)
            t = t.replace("{norm}", ref)
            if snip:
                kind = "snip_in_title"
        parts.append(t.format(**fill))
    return " ".join(parts) or GENERIC[wording][0], kind


def distractor(key: str, wording: str, fill: dict) -> str | None:
    texts = DISTRACTORS[wording].get(key)
    return texts[0].format(**fill) if texts else None


